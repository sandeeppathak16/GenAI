from langchain_core.prompts import ChatPromptTemplate

evaluation_prompt = ChatPromptTemplate.from_template(
    """
You are an expert AI evaluator.

You are given:

1. The original user prompt.
2. The response generated by the routed model (Candidate Response).
3. The response generated by the higher-quality reference model (Reference Response).

Your job is to compare the candidate response against the reference response.

Evaluate the candidate on the following criteria:

- Correctness (0-10)
- Completeness (0-10)
- Clarity (0-10)
- Hallucination (0-10)

Choose one of:

- candidate
- reference
- tie

Return ONLY valid JSON.

{{
    "winner": "candidate",
    "score": 8.5,
    "reason": "Brief explanation"
}}

User Prompt:
{prompt}

Candidate Response:
{candidate}

Reference Response:
{reference}
"""
)


def build_evaluation_prompt(
    prompt: str,
    candidate: str,
    reference: str,
) -> str:
    return evaluation_prompt.format(
        prompt=prompt,
        candidate=candidate,
        reference=reference,
    )